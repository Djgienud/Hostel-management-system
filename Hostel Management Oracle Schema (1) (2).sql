-- ==============================================================================
-- HOSTEL MANAGEMENT SYSTEM - ORACLE DDL SCRIPT
-- Contains: 15 Tables (3NF/BCNF Normalized)
-- Database: Oracle RDBMS (12c and above)
-- ==============================================================================

-- ==========================================
-- DOMAIN 1: Physical Infrastructure & Assets
-- ==========================================

-- 1. Institutions Table
CREATE TABLE institutions (
    institution_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_name VARCHAR2(150) NOT NULL,
    address CLOB,
    contact_no VARCHAR2(20),
    mou_details CLOB,
    mou_contact_person VARCHAR2(100)
);

-- 2. Buildings Table
CREATE TABLE buildings (
    building_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id NUMBER NOT NULL,
    building_name VARCHAR2(100) NOT NULL,
    no_of_floors NUMBER DEFAULT 1 CHECK (no_of_floors > 0),
    FOREIGN KEY (institution_id) REFERENCES institutions(institution_id)
);

-- 3. Hostels Table
CREATE TABLE hostels (
    hostel_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id NUMBER NOT NULL,
    hostel_name VARCHAR2(100) NOT NULL,
    hostel_type VARCHAR2(20) CHECK (hostel_type IN ('Boys', 'Girls', 'Co-ed')),
    warden_name VARCHAR2(100) NOT NULL,
    emergency_contact VARCHAR2(20) NOT NULL,
    FOREIGN KEY (building_id) REFERENCES buildings(building_id)
);

-- 4. Rooms Table
CREATE TABLE rooms (
    room_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id NUMBER NOT NULL,
    room_number VARCHAR2(20) NOT NULL,
    room_type VARCHAR2(30) CHECK (room_type IN ('Single', 'Double', 'Triple')),
    is_ac NUMBER(1) DEFAULT 0 CHECK (is_ac IN (0, 1)), 
    capacity NUMBER NOT NULL CHECK (capacity > 0),
    current_occupancy NUMBER DEFAULT 0,
    room_charge NUMBER(10,2) NOT NULL,
    status VARCHAR2(20) CHECK (status IN ('Available', 'Occupied', 'Maintenance')),
    FOREIGN KEY (hostel_id) REFERENCES hostels(hostel_id)
);

-- 5. Infrastructure Table
CREATE TABLE infrastructure (
    infrastructure_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id NUMBER NOT NULL,
    room_id NUMBER,
    facility_item VARCHAR2(50) NOT NULL,
    condition_status VARCHAR2(30) CHECK (condition_status IN ('New', 'Good', 'Damaged', 'Repair')),
    FOREIGN KEY (hostel_id) REFERENCES hostels(hostel_id),
    FOREIGN KEY (room_id) REFERENCES rooms(room_id)
);

-- ==========================================
-- DOMAIN 2: Pre-Admission Inquiries & Resident Lifecycle
-- ==========================================

-- 6. Inquiries Table
CREATE TABLE inquiries (
    inquiry_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id NUMBER NOT NULL,
    candidate_name VARCHAR2(100) NOT NULL,
    contact_no VARCHAR2(20) NOT NULL,
    preferred_room_type VARCHAR2(30) CHECK (preferred_room_type IN ('Single', 'Double', 'Triple')),
    food_required NUMBER(1) DEFAULT 1 CHECK (food_required IN (0, 1)), 
    period_of_stay VARCHAR2(50),
    status VARCHAR2(30) CHECK (status IN ('Admission', 'No Admission', 'Follow-up')),
    FOREIGN KEY (hostel_id) REFERENCES hostels(hostel_id)
);

-- 7. Candidates Table
CREATE TABLE candidates (
    candidate_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id NUMBER UNIQUE, 
    candidate_name VARCHAR2(100) NOT NULL,
    gender VARCHAR2(10) CHECK (gender IN ('Male', 'Female', 'Other')),
    dob DATE NOT NULL,
    contact_no VARCHAR2(20) NOT NULL UNIQUE,
    permanent_address CLOB NOT NULL,
    parent_details CLOB NOT NULL CHECK (parent_details IS JSON), 
    id_proof_type VARCHAR2(50) NOT NULL,
    id_proof_number VARCHAR2(50) NOT NULL UNIQUE,
    vehicle_info VARCHAR2(50),
    FOREIGN KEY (inquiry_id) REFERENCES inquiries(inquiry_id)
);

-- 8. Admissions Table
CREATE TABLE admissions (
    admission_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id NUMBER NOT NULL,
    hostel_id NUMBER NOT NULL,
    room_id NUMBER NOT NULL,
    admission_date DATE DEFAULT SYSDATE NOT NULL, 
    period_of_stay VARCHAR2(50) NOT NULL,
    mess_opted NUMBER(1) DEFAULT 0 CHECK (mess_opted IN (0, 1)),
    status VARCHAR2(20) CHECK (status IN ('Active', 'On-Leave', 'Exited')),
    FOREIGN KEY (candidate_id) REFERENCES candidates(candidate_id),
    FOREIGN KEY (hostel_id) REFERENCES hostels(hostel_id),
    FOREIGN KEY (room_id) REFERENCES rooms(room_id)
);

-- ==========================================
-- DOMAIN 3: Dining (Mess), Exceptions & Vendors
-- ==========================================

-- 9. Mess Table
CREATE TABLE mess (
    mess_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id NUMBER NOT NULL,
    food_type VARCHAR2(30) CHECK (food_type IN ('Veg', 'Non-Veg', 'Jain')),
    monthly_charge NUMBER(10,2) NOT NULL,
    timings VARCHAR2(150) NOT NULL,
    weekly_schedule CLOB,
    FOREIGN KEY (hostel_id) REFERENCES hostels(hostel_id)
);

-- 10. Mess Exceptions Table
CREATE TABLE mess_exceptions (
    exception_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id NUMBER NOT NULL,
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    reason VARCHAR2(255),
    rebate_applied NUMBER(1) DEFAULT 0 CHECK (rebate_applied IN (0, 1)),
    FOREIGN KEY (candidate_id) REFERENCES candidates(candidate_id)
);

-- 11. Vendors Table
CREATE TABLE vendors (
    vendor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name VARCHAR2(120) NOT NULL,
    vendor_type VARCHAR2(50) NOT NULL,
    contact_no VARCHAR2(20) NOT NULL,
    address CLOB
);

-- ==========================================
-- DOMAIN 4: Billing, Invoicing & Financial
-- ==========================================

-- 12. Payments Table
CREATE TABLE payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id NUMBER NOT NULL,
    invoice_no VARCHAR2(50) NOT NULL UNIQUE,
    payment_type VARCHAR2(30) CHECK (payment_type IN ('Rent', 'Mess', 'Penalty', 'Combined')),
    base_amount NUMBER(10,2) NOT NULL,
    penalty_amount NUMBER(10,2) DEFAULT 0,
    total_amount NUMBER(10,2) GENERATED ALWAYS AS (base_amount + penalty_amount) VIRTUAL,
    payment_mode VARCHAR2(30) CHECK (payment_mode IN ('UPI', 'Cash', 'Net Banking', 'Cheque')),
    payment_status VARCHAR2(20) CHECK (payment_status IN ('Paid', 'Unpaid', 'Partial', 'Overdue')),
    FOREIGN KEY (candidate_id) REFERENCES candidates(candidate_id)
);

-- ==========================================
-- DOMAIN 5: Logs, Grievances & Exits
-- ==========================================

-- 13. Attendance Table
CREATE TABLE attendance (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status VARCHAR2(20) CHECK (status IN ('Present', 'Absent', 'Short Leave', 'Night Out')),
    out_time TIMESTAMP,
    in_time TIMESTAMP,
    remarks VARCHAR2(255),
    FOREIGN KEY (candidate_id) REFERENCES candidates(candidate_id)
);

-- 14. Issues Table
CREATE TABLE issues (
    issue_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id NUMBER NOT NULL,
    issue_category VARCHAR2(50) NOT NULL,
    direction VARCHAR2(10) CHECK (direction IN ('C-H', 'H-C')),
    issue_title VARCHAR2(150) NOT NULL,
    issue_status VARCHAR2(20) CHECK (issue_status IN ('Pending', 'In Process', 'Resolved', 'Closed')),
    FOREIGN KEY (candidate_id) REFERENCES candidates(candidate_id)
);

-- 15. Exit Records Table
CREATE TABLE exit_records (
    exit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id NUMBER NOT NULL,
    exit_date DATE NOT NULL,
    reason CLOB,
    final_settlement NUMBER(10,2) NOT NULL,
    settlement_status VARCHAR2(20) CHECK (settlement_status IN ('Pending', 'Completed', 'Disputed')),
    FOREIGN KEY (candidate_id) REFERENCES candidates(candidate_id)
);